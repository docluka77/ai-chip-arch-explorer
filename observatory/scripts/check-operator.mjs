import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const project=fileURLToPath(new URL('../',import.meta.url));
const dir=fs.existsSync(path.join(project,'dist/index.html'))?path.join(project,'dist'):project;
const sandbox={window:{},document:{querySelector:()=>null,dispatchEvent(){}},cancelAnimationFrame(){},requestAnimationFrame(){return 1;},CustomEvent:class {}};
vm.createContext(sandbox);
for(const f of ['data.js','research-data.js','operator-data.js','operator-provenance.js','operator-context.js','operator.js'])vm.runInContext(fs.readFileSync(path.join(dir,f),'utf8'),sandbox,{filename:f});
const D=sandbox.window.OBS_OPERATOR_DATA,O=sandbox.window.OBS_OPERATOR;
const result=Array.from({length:4},(_,m)=>Array.from({length:4},(_,n)=>D.dot(m,n)));
assert.deepEqual(result,[[3,3,5,3],[5,9,5,7],[6,3,4,5],[4,4,4,4]]);
assert.equal(D.steps.filter(s=>s.id.startsWith('mma')).length,4);
assert.ok(D.steps.findIndex(s=>s.id==='tma')<D.steps.findIndex(s=>s.id==='l2'),'TMA must be issued before its memory request is served');
for(let k=0;k<=4;k++)assert.equal(D.dot(0,0,k),[0,2,2,2,3][k]);
assert.deepEqual(Array.from(D.contract.logical_shapes.B_e),[4608,5120]);
assert.equal(D.geometry.K_loop.mainloop_panels*D.geometry.K_loop.UMMA_substeps_per_panel,160);
assert.equal(D.geometry.per_CTA_mainloop_stage.B_smem.bytes,2*D.geometry.per_CTA_mainloop_stage.B_smem.GMEM_values_FP4_payload_bytes);
assert.equal(D.geometry.threads.per_CTA/32,8);
assert.ok(D.modules.tmem.details.some(t=>t.includes('SM120')),'TMEM architecture boundary must remain visible');
for(const [id,m]of Object.entries(D.modules))for(const ref of m.refs)assert.ok(D.sources.some(s=>s.id===ref),`${id}: ${ref}`);
assert.ok(D.sources.find(s=>s.id==='op-mlp').url.includes('/models/v4_modules/mlp.py'));
const all=sandbox.window.OBS_DATA.sources;
assert.equal(new Set(all.map(s=>s.id)).size,all.length);
for(const mode of ['roce','ib','tcp','local']){const steps=sandbox.window.OBS_CONTEXT.netSteps(mode);assert.equal(steps.length,8);for(const s of steps)assert.ok(s.body.length>20);}
assert.ok(sandbox.window.OBS_CONTEXT.netSteps('roce')[4].body.includes('UDP/IP'));
assert.ok(sandbox.window.OBS_CONTEXT.netSteps('tcp')[3].body.includes('host staging'));
O.restore(new URLSearchParams('opStep=9&opDepth=tensor&opFocus=tmem&opCell=6&opAt=.73&opSpeed=2&opFollow=0'));
let s=O.location();assert.equal(s.step,9);assert.equal(s.cell,6);assert.equal(s.focus,'tmem');assert.equal(s.progress,.73);assert.equal(s.follow,false);assert.equal(s.playing,false);
O.restore(new URLSearchParams('opStep=999&opCell=-9&opAt=88&opSpeed=9&opTab=bad&opNet=bad&opNstep=-5'));
s=O.location();assert.equal(s.step,D.steps.length-1);assert.equal(s.cell,0);assert.equal(s.progress,1);assert.equal(s.speed,1);assert.equal(s.tab,'run');assert.equal(s.net,'roce');assert.equal(s.netStep,0);
const html=fs.readFileSync(path.join(dir,'index.html'),'utf8');for(const [,asset]of html.matchAll(/(?:src|href)="([^"#:]+\.(?:js|css))"/g))assert.ok(fs.existsSync(path.join(dir,asset)),asset);
assert.ok(html.indexOf('operator-provenance.js')<html.indexOf('operator.js'));
console.log(`Operator checks: ${D.steps.length} stages; 4×4 NT result; shape/precision/geometry; ${all.length} sources; 4 network modes; share state bounds.`);
